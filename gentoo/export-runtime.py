"""Export installed runtime packages from the pinned Gentoo build stage.

Uses the Portage API shipped in that stage, including its installed-file database.
Does not install packages or copy the build host's home directories.
"""

import argparse
import os
from pathlib import Path
import re
import subprocess

import portage
from portage.dep import Atom, use_reduce


def dependencies(expression, db):
    """Resolve an already USE-reduced expression against installed packages."""
    if isinstance(expression, str):
        atom = Atom(expression)
        if atom.blocker:
            return set()
        matches = db.match(atom)
        if not matches:
            raise ValueError(f"Runtime dependency is not installed: {atom}")
        return {portage.best(matches)}
    if expression and expression[0] == "||":
        for alternative in expression[1:]:
            try:
                return dependencies(alternative, db)
            except ValueError:
                continue
        raise ValueError(f"No installed runtime alternative: {expression}")
    result = set()
    for item in expression:
        result.update(dependencies(item, db))
    return result


def runtime_packages(roots, db):
    pending = dependencies(roots, db)
    selected = set()
    while pending:
        package = pending.pop()
        if package in selected:
            continue
        selected.add(package)
        use, eapi, rdepend, pdepend = db.aux_get(
            package, ["USE", "EAPI", "RDEPEND", "PDEPEND"]
        )
        for expression in (rdepend, pdepend):
            reduced = use_reduce(
                expression, uselist=use.split(), eapi=eapi, opconvert=True
            )
            pending.update(dependencies(reduced, db) - selected)
    return selected


def export(destination, libc='glibc'):
    destination = Path(destination)
    if not destination.is_absolute() or destination.exists():
        raise ValueError("Export destination must be an absent absolute directory")
    roots = [
        line.strip()
        for line in Path('/usr/local/lib/guit-runtime-packages').read_text().splitlines()
        if line.strip() and not line.lstrip().startswith('#')
    ]
    db = portage.db['/']['vartree'].dbapi
    packages = runtime_packages(roots, db)
    files = set()
    excluded = ('/usr/share/man/', '/usr/share/info/', '/usr/share/locale/')

    def add(path, recursive=False):
        path = os.path.normpath(path)
        if path == '/' or path.startswith(excluded):
            return
        if path in files:
            if recursive and os.path.isdir(path) and not os.path.islink(path):
                for child in Path(path).iterdir():
                    add(str(child), recursive=True)
            return
        if not os.path.lexists(path):
            raise ValueError(f"Required runtime file is missing: {path}")
        # Preserve usrmerge symlinks; never turn /bin into an independent directory.
        parent = os.path.dirname(path)
        add(parent)
        canonical = os.path.join(os.path.realpath(parent), os.path.basename(path))
        if canonical != path:
            add(canonical, recursive=recursive)
            return
        files.add(path)
        if os.path.islink(path):
            target = os.readlink(path)
            if not os.path.isabs(target):
                target = os.path.join(parent, target)
            # /var/lock -> /run/lock and /dev/fd -> /proc/self/fd are
            # intentionally unresolved until the container is started.
            if os.path.lexists(target):
                add(target)
        elif recursive and os.path.isdir(path):
            for child in Path(path).iterdir():
                add(str(child), recursive=True)

    for package in sorted(packages):
        # _dblink belongs to the fixed Portage version in Dockerfile.base.
        for path in db._dblink(package).getcontents():
            # Configuration updates can replace package-owned files/symlinks.
            if os.path.lexists(path):
                add(path)
        add('/var/db/pkg/' + package, recursive=True)

    # Files generated by package configuration rather than listed in CONTENTS.
    generated = [
        '/bin', '/sbin', '/lib', '/lib64', '/usr/sbin',
        '/usr/bin/python', '/usr/bin/python3', '/usr/bin/awk', '/bin/sh',
        '/etc/passwd', '/etc/group', '/etc/nsswitch.conf',
        '/etc/ld.so.conf', '/etc/ld.so.conf.d', '/etc/env.d',
        '/etc/profile.env', '/etc/ssl/certs',
    ]
    if libc == 'musl':
        # The musl stage has no lib64/ldconfig, and uses its own loader path.
        generated = [path for path in generated if os.path.lexists(path)]
        loader_paths = list(Path('/etc').glob('ld-musl-*.path'))
        if not loader_paths:
            raise ValueError('Missing musl loader path configuration')
        generated.extend(str(path) for path in loader_paths)
    for path in generated:
        add(path, recursive=True)

    # Some runtime libraries (notably libgcc_s used by sandbox) are shipped
    # with build-tool packages rather than represented as separate RDEPENDs.
    # Follow the loader's transitive ELF closure without copying the compiler.
    inspected = set()
    libraries = set()
    for path in sorted(files):
        if os.path.islink(path) or not os.path.isfile(path):
            continue
        stat = os.stat(path)
        inode = (stat.st_dev, stat.st_ino)
        if inode in inspected:
            continue
        inspected.add(inode)
        with open(path, 'rb') as stream:
            if stream.read(4) != b'\x7fELF':
                continue
        probe = subprocess.run(['ldd', path], text=True, capture_output=True)
        if 'not found' in probe.stdout or 'Error loading shared library' in probe.stderr:
            raise ValueError(f'Unresolved ELF dependency for {path}: {probe.stdout}{probe.stderr}')
        for library in re.findall(r'(?:=>\s+)?(/\S+)\s+\(0x', probe.stdout):
            libraries.add(library)
            add(library)

    destination.mkdir()
    manifest = Path('/tmp/guit-runtime-files')
    manifest.write_bytes(b''.join(p.lstrip('/').encode() + b'\0' for p in sorted(files)))
    # tar preserves ownership, permissions, symlinks and hardlinks.
    subprocess.run([
        'tar', '-C', '/', '--null', '--no-recursion',
        '-T', str(manifest), '-cpf', '/tmp/guit-runtime.tar',
    ], check=True)
    subprocess.run([
        'tar', '-C', str(destination), '-xpf', '/tmp/guit-runtime.tar',
    ], check=True)
    for path, mode in (
        ('tmp', 0o1777), ('var/tmp', 0o1777), ('proc', 0o755),
        ('sys', 0o755), ('dev', 0o755), ('run', 0o755), ('root', 0o700),
        ('var/cache/edb', 0o755), ('etc/portage', 0o755),
    ):
        target = destination / path
        target.mkdir(parents=True, exist_ok=True)
        target.chmod(mode)
    # Metadata requests provide their own repositories and profile. Use an empty
    # default config instead of retaining the build-time repository or profile.
    (destination / 'etc/portage/repos.conf').write_text('')
    (destination / 'etc/portage/make.conf').write_text('')
    provenance = destination / 'usr/share/gentoo-update-intelligence'
    provenance.mkdir(parents=True, exist_ok=True)
    (provenance / 'runtime-packages.txt').write_text('\n'.join(sorted(packages)) + '\n')
    (provenance / 'runtime-libraries.txt').write_text('\n'.join(sorted(libraries)) + '\n')
    print(f'Exported {len(packages)} packages and {len(files)} paths', flush=True)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('destination')
    parser.add_argument('--libc', choices=('glibc', 'musl'), default='glibc')
    args = parser.parse_args()
    export(args.destination, libc=args.libc)
